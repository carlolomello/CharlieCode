/**
 * Session storage: one JSONL file per conversation.
 *
 * Line 1 is the header, every following line is a message. Append-only in
 * spirit, rewritten atomically on change (files are small), which keeps the
 * format inspectable with `tail -f` and trivially migratable to SQLite later.
 */

export const SESSIONS_DIR = 'sessions'
export const SESSION_EXT = '.jsonl'

export function sessionsDir(platform: Platform): string {
  return platform.configPath(SESSIONS_DIR)
}

function sessionPath(platform: Platform, id: string): string {
  // The id is generated by us (uuid), but a session id may come from the
  // renderer: never let it escape the sessions directory.
  const safe = id.replace(/[^a-zA-Z0-9._-]/g, '')
  return platform.configPath(SESSIONS_DIR, `${safe}${SESSION_EXT}`)
}

function now(): string {
  return new Date().toISOString()
}

/**
 * One writer per session at a time.
 *
 * A streamed answer is persisted while it is still being generated (so a crash
 * does not lose it) and the final version replaces the draft. Without a lock
 * two `read → modify → write` cycles interleave and one silently wins,
 * dropping a message. The lock is a per-session promise chain, not a mutex:
 * different sessions never wait for each other.
 */
const locks = new Map<string, Promise<void>>()

function lockKey(platform: Platform, id: string): string {
  return `${platform.configDir}\u0000${id}`
}

async function withSessionLock<T>(
  platform: Platform,
  id: string,
  task: () => Promise<T>
): Promise<T> {
  const key = lockKey(platform, id)
  const previous = locks.get(key) ?? Promise.resolve()
  let release: () => void = () => undefined
  const gate = new Promise<void>((resolve) => {
    release = resolve
  })
  const tail = previous.then(() => gate)
  locks.set(key, tail)

  await previous.catch(() => undefined)
  try {
    return await task()
  } finally {
    release()
    // Drop the entry only when nobody queued behind us.
    if (locks.get(key) === tail) locks.delete(key)
  }
}

/**
 * `listSessions` runs on every window focus and after every turn. Parsing all
 * JSONL files each time is wasted work on long chats, so summaries are cached
 * by file mtime + size: a write always changes at least one of them.
 */
interface SummaryCacheEntry {
  mtimeMs: number
  size: number
  summary: SessionSummary
}

const summaryCache = new Map<string, SummaryCacheEntry>()

function invalidateSummary(platform: Platform, id: string): void {
  summaryCache.delete(lockKey(platform, id))
}

/** First meaningful line of the first user message, trimmed for the sidebar. */
export function deriveTitle(text: string): string {
  const firstLine =
    text
      .split('\n')
      .map((line) => line.trim())
      .find((line) => line.length > 0) ?? 'Nuova chat'
  return firstLine.length > 64 ? `${firstLine.slice(0, 63)}…` : firstLine
}

async function writeAtomic(path: string, content: string): Promise<void> {
  // A rename on Windows fails with EPERM while another handle holds the file,
  // and a failed save aborted the whole turn. The helper retries and falls
  // back to an in-place write.
  await writeFileAtomic(path, content)
}

function toHeader(session: Session): SessionHeader {
  const { messages: _messages, ...header } = session
  return header
}

function serialize(header: SessionHeader, messages: StoredMessage[]): string {
  const lines = [JSON.stringify(header), ...messages.map((message) => JSON.stringify(message))]
  return `${lines.join('\n')}\n`
}

function isHeader(value: unknown): value is SessionHeader {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  return typeof record.id === 'string' && typeof record.title === 'string'
}

function isMessage(value: unknown): value is StoredMessage {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  return typeof record.role === 'string' && typeof record.content === 'string'
}

export async function createSession(
  platform: Platform,
  input: NewSessionInput = {}
): Promise<Session> {
  const createdAt = now()
  const session: Session = {
    id: input.id ?? randomUUID(),
    title: input.title ?? 'Nuova chat',
    createdAt,
    updatedAt: createdAt,
    workspacePath: input.workspacePath,
    modelKey: input.modelKey,
    effort: input.effort ?? 'none',
    messages: []
  }

  await mkdir(sessionsDir(platform), { recursive: true })
  await writeAtomic(sessionPath(platform, session.id), serialize(toHeader(session), []))
  invalidateSummary(platform, session.id)
  return session
}

export async function readSession(platform: Platform, id: string): Promise<Session | undefined> {
  const path = sessionPath(platform, id)
  if (!existsSync(path)) return undefined

  const raw = await readFile(path, 'utf8')
  const lines = raw.split('\n').filter((line) => line.trim().length > 0)
  if (lines.length === 0) return undefined

  let header: SessionHeader | undefined
  const messages: StoredMessage[] = []

  for (const line of lines) {
    let parsed: unknown
    try {
      parsed = JSON.parse(line)
    } catch {
      // A torn last line must not destroy the whole conversation.
      continue
    }
    if (!header) {
      if (!isHeader(parsed)) return undefined
      header = parsed
      continue
    }
    if (isMessage(parsed)) messages.push(parsed)
  }

  if (!header) return undefined
  return { ...header, messages }
}

export async function listSessions(platform: Platform): Promise<SessionSummary[]> {
  const dir = sessionsDir(platform)
  if (!existsSync(dir)) return []

  const entries = await readdir(dir)
  const summaries: SessionSummary[] = []

  for (const entry of entries) {
    if (!entry.endsWith(SESSION_EXT)) continue
    const id = entry.slice(0, -SESSION_EXT.length)
    const path = sessionPath(platform, id)
    const info = await stat(path).catch(() => undefined)
    if (!info) continue

    const key = lockKey(platform, id)
    const cached = summaryCache.get(key)
    if (cached && cached.mtimeMs === info.mtimeMs && cached.size === info.size) {
      summaries.push(cached.summary)
      continue
    }

    const session = await readSession(platform, id)
    if (!session) continue

    const lastMessage = [...session.messages].reverse().find((message) => message.content.trim())
    const summary: SessionSummary = {
      id: session.id,
      title: session.title,
      createdAt: session.createdAt,
      updatedAt: session.updatedAt,
      workspacePath: session.workspacePath,
      modelKey: session.modelKey,
      effort: session.effort,
      messageCount: session.messages.length,
      preview: (lastMessage?.content ?? '').replace(/\s+/g, ' ').slice(0, 120)
    }
    summaryCache.set(key, { mtimeMs: info.mtimeMs, size: info.size, summary })
    summaries.push(summary)
  }

  summaries.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
  return summaries
}

export async function saveSession(platform: Platform, session: Session): Promise<void> {
  await mkdir(sessionsDir(platform), { recursive: true })
  await writeAtomic(
    sessionPath(platform, session.id),
    serialize({ ...toHeader(session), updatedAt: session.updatedAt || now() }, session.messages)
  )
  invalidateSummary(platform, session.id)
}

async function appendMessageUnlocked(
  platform: Platform,
  id: string,
  message: StoredMessage
): Promise<Session> {
  const session = (await readSession(platform, id)) ?? (await createSession(platform, { id }))
  session.messages.push(message)
  session.updatedAt = message.createdAt || now()

  // The first user message names the conversation, like every chat app does.
  if (session.title === 'Nuova chat' && message.role === 'user' && message.content.trim()) {
    session.title = deriveTitle(message.content)
  }

  await saveSession(platform, session)
  return session
}

export async function appendMessage(
  platform: Platform,
  id: string,
  message: StoredMessage
): Promise<Session> {
  return withSessionLock(platform, id, () => appendMessageUnlocked(platform, id, message))
}

/**
 * Inserts a message or replaces the one with the same id.
 *
 * A streaming answer is written as a draft while it grows; the final version
 * has the same id and must replace the draft, not be appended after it.
 */
async function upsertMessageUnlocked(
  platform: Platform,
  id: string,
  message: StoredMessage
): Promise<Session> {
  const session = (await readSession(platform, id)) ?? (await createSession(platform, { id }))
  const index = session.messages.findIndex((existing) => existing.id === message.id)

  if (index >= 0) {
    session.messages[index] = message
  } else {
    session.messages.push(message)
    if (session.title === 'Nuova chat' && message.role === 'user' && message.content.trim()) {
      session.title = deriveTitle(message.content)
    }
  }

  session.updatedAt = message.createdAt || now()
  await saveSession(platform, session)
  return session
}

export async function upsertMessage(
  platform: Platform,
  id: string,
  message: StoredMessage
): Promise<Session> {
  return withSessionLock(platform, id, () => upsertMessageUnlocked(platform, id, message))
}

export async function updateSession(
  platform: Platform,
  id: string,
  patch: SessionPatch
): Promise<Session | undefined> {
  return withSessionLock(platform, id, async () => {
    const session = await readSession(platform, id)
    if (!session) return undefined

    if (patch.title !== undefined) session.title = patch.title
    if (patch.modelKey !== undefined) session.modelKey = patch.modelKey
    if (patch.effort !== undefined) session.effort = patch.effort
    if (patch.workspacePath !== undefined) session.workspacePath = patch.workspacePath
    session.updatedAt = now()

    await saveSession(platform, session)
    return session
  })
}

export async function deleteSession(platform: Platform, id: string): Promise<boolean> {
  return withSessionLock(platform, id, async () => {
    const path = sessionPath(platform, id)
    if (!existsSync(path)) return false
    await rm(path, { force: true })
    invalidateSummary(platform, id)
    return true
  })
}

/** Messages that go to the model: no errors, no empty turns, most recent last. */
export function toChatHistory(session: Session, limit = 40): ChatMessage[] {
  const history = session.messages
    .filter((message) => message.content.trim().length > 0 || (message.attachments?.length ?? 0) > 0)
    .filter((message) => !message.error)
    .slice(-limit)
    .map((message) => ({
      role: message.role,
      content: message.content,
      ...(message.attachments?.length ? { attachments: message.attachments } : {})
    }))

  // A resend writes the same user message twice. The model reads the duplicate
  // as "the user keeps repeating" and starts answering about the repetition
  // instead of the question.
  return history.filter(
    (message, index) =>
      index === 0 ||
      !(
        message.role === 'user' &&
        history[index - 1]?.role === 'user' &&
        history[index - 1]?.content.trim() === message.content.trim()
      )
  )
}
